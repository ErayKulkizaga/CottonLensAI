"""Actual fit-entry/cache routing with generated frames and no estimator."""
from types import SimpleNamespace

import pandas as pd
import pytest
from cottonlens_ml.research import engine
from cottonlens_ml.research.admission import AdmissionError, model_inputs_id
from cottonlens_ml.research.ledger import Ledger

from ml.tests.admission_fixture import synthetic_admitter


def fixture(root, monkeypatch):
    history = pd.DataFrame({'date': pd.bdate_range('2000-01-03', periods=10), 'x': 1.})
    train, validation, test = history.iloc[:3].copy(), history.iloc[3:5].copy(), history.iloc[6:8].copy()
    recipe = {'family': 'ridge', 'horizon': 1, 'features': ['x']}
    exp = object.__new__(engine.Experiment)
    exp.root, exp.history, exp.identity = root, history, {'profile': 'generated-fit-cache', 'admission_policy': 1}
    exp.ledger = Ledger(root/'ledger', exp.identity)
    calls = []
    def compute(history, train, validation, test, recipe, workspace, **kwargs):
        calls.append(1)
        (workspace/'generated.json').write_text('generated bytes, no fitted model')
        return {'predictions': test.x.tolist()}
    monkeypatch.setattr(engine, 'fit_predict', compute)
    exp.admission = synthetic_admitter(root/'admission', exp.identity,
        model_inputs=model_inputs_id(history, train, validation, test, recipe, 1))
    return SimpleNamespace(experiment=exp, train=train, validation=validation, test=test,
                           recipe=recipe, calls=calls)


def run(case):
    return case.experiment.fit(case.recipe, case.train, case.validation, case.test,
                               'generated-control', iterations=1)


@pytest.mark.parametrize('changed', ['history', 'validation', 'test'])
def test_stale_admission_cannot_reuse_fit_with_changed_actual_inputs(tmp_path, monkeypatch, changed):
    case = fixture(tmp_path, monkeypatch)
    first = run(case)
    assert run(case) == first and case.calls == [1]
    frame = case.experiment.history if changed == 'history' else getattr(case, changed)
    frame.loc[frame.index[0], 'x'] = 99.
    with pytest.raises(AdmissionError, match='inputs changed|specification'):
        run(case)
    assert case.calls == [1]


@pytest.mark.parametrize('changed', ['history', 'validation', 'test'])
def test_explicit_new_input_admission_uses_a_different_fit_identity(tmp_path, monkeypatch, changed):
    case = fixture(tmp_path, monkeypatch)
    first = run(case)
    frame = case.experiment.history if changed == 'history' else getattr(case, changed)
    frame.loc[frame.index[0], 'x'] = 99.
    case.experiment.admission = synthetic_admitter(tmp_path/'new-admission', case.experiment.identity,
        model_inputs=model_inputs_id(case.experiment.history, case.train, case.validation,
                                     case.test, case.recipe, 1))
    second = run(case)
    assert second['experiment_id'] != first['experiment_id']
    assert case.calls == [1, 1]


@pytest.mark.parametrize('change', ['dtype', 'order', 'missing_validation'])
def test_actual_input_structure_is_rechecked_before_cache(tmp_path, monkeypatch, change):
    case = fixture(tmp_path, monkeypatch)
    run(case)
    if change == 'dtype':
        case.test['x'] = case.test.x.astype('float32')
    elif change == 'order':
        case.test = case.test.iloc[::-1].copy()
    else:
        case.validation = None
    with pytest.raises(AdmissionError):
        run(case)
    assert case.calls == [1]


def test_cached_fit_requires_current_admission_even_when_no_compute_needed(tmp_path, monkeypatch):
    case = fixture(tmp_path, monkeypatch)
    run(case)
    case.experiment.admission = None
    with pytest.raises(AdmissionError, match='Exact input admission'):
        run(case)
    assert case.calls == [1]


def test_staged_upload_retry_preserves_input_binding_and_never_recomputes(tmp_path, monkeypatch):
    from cottonlens_ml.research import ledger
    case = fixture(tmp_path, monkeypatch)
    copy = ledger.shutil.copyfile
    def unavailable(*args, **kwargs):
        raise OSError('Generated upload failure')
    monkeypatch.setattr(ledger.shutil, 'copyfile', unavailable)
    with pytest.raises(OSError, match='upload failure'):
        run(case)
    case.test['x'] = 99.
    with pytest.raises(AdmissionError):
        run(case)
    assert case.calls == [1]
    case.test['x'] = 1.
    monkeypatch.setattr(ledger.shutil, 'copyfile', copy)
    result = run(case)
    assert result['specification']['model_inputs_schema'] == 2
    assert case.calls == [1]
